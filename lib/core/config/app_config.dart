import '../logging/app_logger.dart';

enum AppEnvironment {
  dev,
  staging,
  prod;

  static AppEnvironment parse(String value) => AppEnvironment.values.firstWhere(
    (e) => e.name == value.toLowerCase(),
    orElse: () => AppEnvironment.dev,
  );
}

/// Non-secret application configuration.
///
/// Values come from compile-time `--dart-define` flags so nothing is
/// hard-coded in feature code, for example:
///
///     flutter run --dart-define=APP_ENV=staging
///
/// Never put API keys, passwords or tokens here. Firebase options will be
/// added in the Firebase phase, using the platform config files generated by
/// the Firebase tooling.
class AppConfig {
  const AppConfig({
    this.environment = AppEnvironment.dev,
    this.appName = 'NoteVault',
  });

  factory AppConfig.fromEnvironment() => AppConfig(
    environment: AppEnvironment.parse(
      const String.fromEnvironment('APP_ENV', defaultValue: 'dev'),
    ),
  );

  final AppEnvironment environment;
  final String appName;

  bool get isProduction => environment == AppEnvironment.prod;

  /// Verbose logs in dev/staging, warnings and errors only in production.
  LogLevel get minLogLevel => isProduction ? LogLevel.warning : LogLevel.debug;
}
